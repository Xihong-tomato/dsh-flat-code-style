export const name = 'flat-code-style';
export const inject = ['systemPrompt'];

export function apply(ctx) {
  ctx.systemPrompt.section({
    name: 'user-preference:flat-code-style',
    order: 10300,
    interpolate: false,
    text: `编写和修改代码时遵守以下用户编码风格偏好：
1. 尽可能使用扁平、直接、按执行顺序展开的代码。非必要时不定义辅助函数，直接在 main 或对应语言的主执行流程中完成任务。
2. Python 脚本优先在 if __name__ == "__main__": 下直接编写主流程；Notebook 直接在单元格中编写。不要为了包装入口额外定义 main()。
3. 不生成逻辑过于简单且函数体有效代码少于 5 行的辅助函数。有效代码不包括空行、纯注释、文档字符串、单独的括号。不得用无用语句、注释或人为拆行凑够 5 行。
4. 简单计算、一次性读取、参数设置、格式转换、打印和绘图步骤直接写在使用位置。用简洁分段注释组织流程，不为形式上的模块化增加函数、类或多层调用。
5. 只有框架必需的入口或回调、递归、必须传入 callable、确实需要复用的复杂逻辑等必要情形，才定义函数。必要短回调允许保留，简要说明必要性，不要人为增加行数。
6. 扁平化不得改变计算结果、异常处理、资源释放或必要接口。修改已有项目时保留必需接口，仅在任务范围内简化。
7. 输出前自查：内联不必要的辅助函数，删除过度封装，确保主流程可从上到下直接阅读。`,
  });
}
